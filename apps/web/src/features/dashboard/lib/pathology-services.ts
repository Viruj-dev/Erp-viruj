const existingCodes: Record<string, string> = {
  "Complete Blood Count (CBC)": "CBC",
  "ESR (Erythrocyte Sedimentation Rate)": "ESR",
  "Liver Function Test (LFT)": "LFT",
  "Kidney Function Test (KFT/RFT)": "KFT",
  "Lipid Profile": "LIPID",
  "Thyroid Profile": "THYROID",
  "Vitamin D": "VITD",
  "Urine Culture": "UCULT",
  "Urine Routine and Microscopy": "URINE",
};

export const pathologyServicePresets = Object.entries(
  pathologyServiceGroups
).flatMap(([category, names]) =>
  names.map((name) => ({
    category,
    name,
    code:
      existingCodes[name] ??
      name
        .toUpperCase()
        .replace(/[^A-Z0-9]+/g, "-")
        .replace(/-$/, "")
        .slice(0, 40),
    specimen: "",
  }))
);
